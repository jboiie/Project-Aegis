def test_recommendation_adaptive_vs_fixed_requires_pair_above_encoding(tmp_path):
    pair_wins = [_result("pair", True, iterations_to_bypass=2)] * 5 + [_result("encoding", False)] * 5
    pair_loses = [_result("pair", False)] * 5 + [_result("encoding", True)] * 5

    md_wins = generate(_meta(), pair_wins, str(tmp_path / "a.md"))
    md_loses = generate(_meta(), pair_loses, str(tmp_path / "b.md"))

    assert "Adaptive attacks significantly outperform" in md_wins
    assert "Adaptive attacks significantly outperform" not in md_loses


