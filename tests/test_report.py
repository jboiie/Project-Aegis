"""Tests for redteam/report.py — Markdown rendering, no Supabase/network involved."""

import os

import pytest

from redteam.attacks.base import AttackResult
from redteam.report import BYPASS_CAP, CampaignMeta, generate


def _result(strategy, bypassed, response="[BLOCKED] L1 Regex match", **metadata):
    return AttackResult(
        strategy=strategy,
        prompt=f"prompt for {strategy}",
        response=response,
        bypassed=bypassed,
        confidence=0.9,
        metadata=metadata,
        timestamp="2026-08-01T00:00:00+00:00",
    )


def _meta(**overrides):
    defaults = dict(
        campaign_id="test-campaign-id",
        target="http://localhost:8000/v1/chat/completions",
        date="2026-08-01T00:00:00+00:00",
        attacks=["template", "encoding", "pair"],
        fail_above=20.0,
    )
    defaults.update(overrides)
    return CampaignMeta(**defaults)


@pytest.fixture
def mixed_results():
    return [
        _result("template", False, response="[BLOCKED] L1 Regex match"),
        _result("template", True, response="Sure, here's how..."),
        _result("encoding", False, response="[BLOCKED] L2 DeBERTa injection"),
        _result("pair", True, response="Sure, here's the answer.", iterations_to_bypass=3),
        _result("pair", False, response="[BLOCKED] SessionGuard lockout"),
    ]


def test_all_section_headings_render(tmp_path, mixed_results):
    out = tmp_path / "report.md"
    md = generate(_meta(), mixed_results, str(out))

    for heading in [
        "# Aegis Red-Team Report",
        "## Executive Summary",
        "## Results by Strategy",
        "## Bypassed Prompts (Full Detail)",
        "## Blocked Attacks Summary",
        "## Recommendations",
        "Generated by Aegis",
    ]:
        assert heading in md


def test_writes_file_and_creates_parent_dirs(tmp_path, mixed_results):
    out = tmp_path / "nested" / "dir" / "report.md"
    generate(_meta(), mixed_results, str(out))
    assert out.exists()
    assert out.read_text(encoding="utf-8") != ""


def test_header_fields(tmp_path, mixed_results):
    md = generate(_meta(), mixed_results, str(tmp_path / "r.md"))
    assert "test-campaign-id" in md
    assert "http://localhost:8000/v1/chat/completions" in md
    assert "Total Attempts:** 5" in md


def test_bypass_cap_triggers_truncation_note(tmp_path):
    results = [_result("template", True, response=f"ok {i}") for i in range(BYPASS_CAP + 5)]
    md = generate(_meta(), results, str(tmp_path / "r.md"))
    assert f"Showing first {BYPASS_CAP} bypasses" in md
    assert md.count("### Bypass #") == BYPASS_CAP


def test_bypass_cap_not_triggered_under_limit(tmp_path):
    results = [_result("template", True, response=f"ok {i}") for i in range(3)]
    md = generate(_meta(), results, str(tmp_path / "r.md"))
    assert "Showing first" not in md
    assert md.count("### Bypass #") == 3


def test_recommendation_renders_only_when_template_bypassed(tmp_path):
    with_bypass = [_result("template", True), _result("encoding", False)]
    without_bypass = [_result("template", False), _result("encoding", False)]

    md_with = generate(_meta(), with_bypass, str(tmp_path / "a.md"))
    md_without = generate(_meta(), without_bypass, str(tmp_path / "b.md"))

    assert "Template attacks bypassed" in md_with
    assert "Template attacks bypassed" not in md_without


